"""Generate DAORecomp/kernel/import_stubs.cpp: a weak definition for every
__imp__ import the recompiled code references. Real implementations elsewhere
override these; unimplemented ones log once and return 0."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
shared = (root / "ppc" / "ppc_recomp_shared.h").read_text()
names = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\);", shared)))

out = ["// Generated by scripts/gen_stubs.py - do not edit.",
       '#include "stdafx.h"',
       '#include "function.h"',
       "",
       "#define DAO_WEAK_STUB(name) \\",
       "    __attribute__((weak)) PPC_FUNC(__imp__##name) { (void)base; ::dao::ReportStub(#name, ctx); ctx.r3.u64 = 0; }",
       ""]
out += [f"DAO_WEAK_STUB({n})" for n in names]
(root / "DAORecomp" / "kernel" / "import_stubs.cpp").write_text("\n".join(out) + "\n")
print(f"{len(names)} import stubs")
